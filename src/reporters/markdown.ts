import { AssessmentRecord } from '../types/index.js';

export function formatMarkdownReport(assessment: AssessmentRecord): string {
  const { decision, findings, durationMs } = assessment;

  let badge = '🔴 BLOCKED';
  if (decision.state === 'READY') badge = '🟢 READY TO SHIP';
  if (decision.state === 'READY_WITH_WARNINGS') badge = '🟡 READY WITH WARNINGS';
  if (decision.state === 'INCOMPLETE') badge = '⚪ INCOMPLETE';

  let md = `# ShipGuard Release Readiness Report\n\n`;
  md += `**Project:** \`${assessment.projectName}\`  \n`;
  md += `**Date:** ${new Date(assessment.timestamp).toUTCString()}  \n`;
  md += `**Duration:** ${(durationMs / 1000).toFixed(2)}s  \n`;
  md += `**Status:** **${badge}**  \n`;
  md += `**Quality Score:** **${decision.score}/100**  \n\n`;

  md += `> ${decision.summary}\n\n`;

  md += `## 🛡️ Mandatory Release Gates\n\n`;
  md += `| Gate | Mandatory | Status | Details |\n`;
  md += `| :--- | :---: | :---: | :--- |\n`;
  for (const g of decision.gates) {
    const icon = g.passed ? '✅ Passed' : '❌ Failed';
    const req = g.mandatory ? '**Yes**' : 'No';
    md += `| ${g.title} | ${req} | ${icon} | ${g.reason} |\n`;
  }
  md += `\n`;

  md += `## 📊 Category Breakdown\n\n`;
  md += `| Category | Score | Weight | Checks | Status |\n`;
  md += `| :--- | :---: | :---: | :---: | :---: |\n`;
  for (const [cat, cs] of Object.entries(decision.categoryScores)) {
    const statusText = cs.status.toUpperCase();
    md += `| ${cat.replace(/_/g, ' ')} | ${cs.score}/100 | ${cs.weight}% | ${cs.checksPassed}/${cs.checksTotal} | ${statusText} |\n`;
  }
  md += `\n`;

  md += `## 🔍 Detected Findings (${findings.length})\n\n`;
  if (findings.length === 0) {
    md += `*No quality or security findings detected. Clean release!* 🎉\n`;
  } else {
    md += `| Severity | Rule ID | Title | File | Status |\n`;
    md += `| :---: | :---: | :--- | :--- | :---: |\n`;
    for (const f of findings) {
      const loc = f.file ? `\`${f.file}${f.line ? `:${f.line}` : ''}\`` : '-';
      md += `| **${f.severity}** | \`${f.ruleId}\` | ${f.title} | ${loc} | \`${f.status}\` |\n`;
    }
  }

  md += `\n---\n*Report generated by [ShipGuard](https://github.com/0xyz-exe/shipguard) — Know your release is ready before you ship.*\n`;

  return md;
}
